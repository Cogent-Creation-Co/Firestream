#!/usr/bin/env bash
# check-embedded-sync.sh — guard the embedded duplicate of the container tree.
#
# ── WHAT IS DUPLICATED ───────────────────────────────────────────────
# src/lib/rust/nix-container-builder/embedded/ is a byte-for-byte copy of the
# directories listed in that crate's build.rs (`EMBEDDED_DIRS`), currently:
#
#     bin/nix/firestream
#     src/containers/firestream
#     flake.nix  flake.lock
#
# It exists because the Rust container builder ships a self-contained Nix
# workspace: at runtime it materialises `embedded/` into a temp dir and builds
# images from THAT, never from the repo it happens to be sitting in.
#
# ── WHY THIS CHECK EXISTS ────────────────────────────────────────────
# The copy is generated by build.rs and is .gitignored, so it is not a
# committed duplicate that can rot in review. It CAN still diverge, in two
# ways, both silent:
#
#   1. cargo did not re-run build.rs (stale target/, an incremental build that
#      skipped the crate, a cached CI artifact, a prebuilt binary shipped with
#      an older embedded tree). The builder then produces images from whatever
#      the container tree looked like at the last rebuild.
#   2. A canonical file is FILTERED OUT by the embedder. build.rs runs with
#      respect_gitignore(true) + respect_dockerignore(true) and explicit
#      excludes for *.pyc, __pycache__, node_modules, target, .venv, result,
#      result-*. Add a container file whose path matches any of those — or that
#      any .gitignore in the tree happens to cover — and it is simply absent
#      from the embedded workspace. The canonical tree then evaluates fine
#      locally while `nix-container-builder` evaluates a tree missing an
#      import.
#
# Case 2 is the nasty one, and it is exactly what a normal `cargo build` will
# not tell you. This script catches both by regenerating and diffing.
#
# ── WHAT IT DOES ─────────────────────────────────────────────────────
#   1. `cargo build -p nix-container-builder` (regenerates embedded/).
#   2. `diff -r` every embedded directory against its canonical source.
#
# Step 1 is what makes step 2 meaningful: without it we would only be
# comparing a stale copy against itself.
#
# Usage:
#   bash bin/build/check-embedded-sync.sh          # regenerate, then diff
#   bash bin/build/check-embedded-sync.sh --no-build   # diff only (fast; assumes fresh)
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
EMBEDDED="$REPO_ROOT/src/lib/rust/nix-container-builder/embedded"

# Kept in step with EMBEDDED_DIRS in
# src/lib/rust/nix-container-builder/build.rs. A directory listed there but not
# here is simply unguarded, not broken -- but add it.
EMBEDDED_DIRS=(
    "bin/nix/firestream"
    "src/containers/firestream"
)
EMBEDDED_FILES=(
    "flake.nix"
    "flake.lock"
)

DO_BUILD=1
if [[ "${1:-}" == "--no-build" ]]; then
    DO_BUILD=0
fi

if [[ "$DO_BUILD" -eq 1 ]]; then
    echo "==> regenerating embedded/ (cargo build -p nix-container-builder)"
    (cd "$REPO_ROOT" && cargo build -p nix-container-builder)
fi

if [[ ! -d "$EMBEDDED" ]]; then
    echo "ERROR: $EMBEDDED does not exist." >&2
    echo "       Generate it with: cargo build -p nix-container-builder" >&2
    exit 1
fi

status=0

for d in "${EMBEDDED_DIRS[@]}"; do
    if [[ ! -d "$EMBEDDED/$d" ]]; then
        echo "ERROR: embedded/$d is missing entirely." >&2
        status=1
        continue
    fi
    echo "==> diff -r $d"
    if ! diff -r "$REPO_ROOT/$d" "$EMBEDDED/$d"; then
        status=1
    fi
done

for f in "${EMBEDDED_FILES[@]}"; do
    echo "==> diff $f"
    if ! diff "$REPO_ROOT/$f" "$EMBEDDED/$f"; then
        status=1
    fi
done

if [[ "$status" -ne 0 ]]; then
    cat >&2 <<'EOF'

ERROR: the embedded Nix workspace has diverged from the canonical tree.

  canonical: <repo>/{bin/nix/firestream, src/containers/firestream, flake.*}
  embedded:  <repo>/src/lib/rust/nix-container-builder/embedded/...

  The Rust container builder builds images from the EMBEDDED copy, so this
  divergence means `nix-container-builder` and `nix build .#<container>` can
  produce different images with no error anywhere.

  If a file is listed as "Only in <canonical>", the embedder FILTERED IT OUT:
  build.rs runs with respect_gitignore(true) / respect_dockerignore(true) plus
  excludes for *.pyc __pycache__ node_modules target .venv result result-*.
  Either rename the file out of those patterns, or teach build.rs about it.

  If the contents differ, embedded/ is stale -- force a rebuild:

      touch src/lib/rust/nix-container-builder/build.rs
      bash bin/build/check-embedded-sync.sh

EOF
    exit 1
fi

echo "OK: embedded workspace matches the canonical tree."
