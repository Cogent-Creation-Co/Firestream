# mix-deps.exs — write a mix-deps.nix from a mix.lock.
# Copyright Firestream. MIT License.
#
# Each lock entry becomes one fetch, so a lock change refetches only the
# changed packages:
#   - a Hex package: fetchHex with the outer checksum of the lock, which is
#     the SHA-256 of the tarball on repo.hex.pm;
#   - a Git dependency on GitHub: fetchFromGitHub at the commit of the lock.
#
# A mix.lock holds no content hash for a Git dependency. The script takes it
# from the current mix-deps.nix when the owner, repo and commit match, and
# else asks `nix flake prefetch` (only with --prefetch). Without --prefetch a
# missing hash is an error, so the offline check fails on a stale file.
#
# Usage:
#   elixir mix-deps.exs --lock PATH --label TEXT [--hashes-from PATH] [--prefetch]
# The result goes to stdout.

defmodule MixDeps do
  @generator "bin/nix/firestream/beam/mix-deps.sh"

  def main(argv) do
    {opts, [], []} =
      OptionParser.parse(argv,
        strict: [lock: :string, label: :string, hashes_from: :string, prefetch: :boolean]
      )

    lock = read_lock(Keyword.fetch!(opts, :lock))
    known = known_hashes(opts[:hashes_from])

    entries =
      lock
      |> Enum.sort_by(fn {name, _} -> to_string(name) end)
      |> Enum.map(fn {name, entry} -> render(to_string(name), entry, known, opts[:prefetch]) end)

    IO.write("""
    # WARNING: generated by #{@generator} from the mix.lock of
    # #{Keyword.fetch!(opts, :label)}. A hand edit fails the mix-deps check.
    { fetchHex, fetchFromGitHub }:
    {
    #{Enum.join(entries)}}
    """)
  end

  defp read_lock(path) do
    {map, _} = path |> File.read!() |> Code.string_to_quoted!(emit_warnings: false) |> Code.eval_quoted()
    map
  end

  defp known_hashes(nil), do: %{}

  defp known_hashes(path) do
    if File.exists?(path) do
      ~r/owner = "([^"]+)";\s*repo = "([^"]+)";\s*rev = "([0-9a-f]{40})";\s*hash = "([^"]+)";/
      |> Regex.scan(File.read!(path), capture: :all_but_first)
      |> Map.new(fn [owner, repo, rev, hash] -> {{owner, repo, rev}, hash} end)
    else
      %{}
    end
  end

  defp render(name, {:hex, pkg, version, _inner, _managers, _deps, "hexpm", outer}, _, _) do
    """
      #{attr(name)} = fetchHex {
        pkg = "#{pkg}";
        version = "#{version}";
        sha256 = "#{outer}";
      };
    """
  end

  defp render(name, {:git, url, rev, _opts}, known, prefetch) do
    {owner, repo} = github!(name, url)
    hash = Map.get_lazy(known, {owner, repo, rev}, fn -> prefetch!(name, owner, repo, rev, prefetch) end)

    """
      #{attr(name)} = fetchFromGitHub {
        owner = "#{owner}";
        repo = "#{repo}";
        rev = "#{rev}";
        hash = "#{hash}";
      };
    """
  end

  defp render(name, entry, _, _) do
    fail("#{name}: unsupported lock entry #{inspect(elem(entry, 0))}; only hexpm and GitHub Git deps are supported")
  end

  defp github!(name, url) do
    case Regex.run(~r{^https://github\.com/([^/]+)/([^/]+?)(\.git)?/?$}, url) do
      [_, owner, repo | _] -> {owner, repo}
      nil -> fail("#{name}: #{url} is not a GitHub repository")
    end
  end

  defp prefetch!(name, owner, repo, rev, true) do
    {out, 0} = System.cmd("nix", ["flake", "prefetch", "--json", "github:#{owner}/#{repo}/#{rev}"])
    [_, hash] = Regex.run(~r/"hash":"([^"]+)"/, out) || fail("#{name}: no hash in nix output")
    hash
  end

  defp prefetch!(name, owner, repo, rev, _) do
    fail("#{name}: no hash for github:#{owner}/#{repo}/#{rev}; the file is stale, run #{@generator}")
  end

  defp attr(name) do
    if Regex.match?(~r/^[A-Za-z_][A-Za-z0-9_'-]*$/, name), do: name, else: ~s("#{name}")
  end

  defp fail(message) do
    IO.puts(:stderr, "mix-deps: " <> message)
    System.halt(1)
  end
end

MixDeps.main(System.argv())
